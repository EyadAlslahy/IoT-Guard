# جدول P-Box الرسمي لـ PRESENT
# يُحدد الوجهة الجديدة لكل بت: PBOX[i] = المكان الذي ينتقل إليه البت i
PBOX = [
    0, 16, 32, 48, 1, 17, 33, 49,        # البتات 0..7   → أماكنها الجديدة
    2, 18, 34, 50, 3, 19, 35, 51,        # البتات 8..15
    4, 20, 36, 52, 5, 21, 37, 53,        # البتات 16..23
    6, 22, 38, 54, 7, 23, 39, 55,        # البتات 24..31
    8, 24, 40, 56, 9, 25, 41, 57,        # البتات 32..39
    10, 26, 42, 58, 11, 27, 43, 59,      # البتات 40..47
    12, 28, 44, 60, 13, 29, 45, 61,      # البتات 48..55
    14, 30, 46, 62, 15, 31, 47, 63       # البتات 56..63
]

# جدول P-Box العكسي (لفك التشفير)
PBOX_INV = [0] * 64                      # مصفوفة فارغة بحجم 64
for i, p in enumerate(PBOX):             # نمر على كل عنصر في PBOX
    PBOX_INV[p] = i                      # نضع العكس: الموضع p جاء من i


def apply_pbox(state):
    """تطبيق P-Box على 64 بت (إعادة ترتيب البتات)"""
    result = 0                                     # الناتج يبدأ صفر
    for i in range(64):                            # نمر على 64 بت
        bit = (state >> i) & 1                     # استخراج البت رقم i
        if bit:                                    # إذا كان البت = 1
            result |= 1 << PBOX[i]                 # ضعه في مكانه الجديد
    return result                                  # إرجاع الحالة الجديدة


def apply_pbox_inv(state):
    """تطبيق P-Box العكسي (لفك التشفير)"""
    result = 0                                     # الناتج يبدأ صفر
    for i in range(64):                            # نمر على 64 بت
        bit = (state >> i) & 1                     # استخراج البت رقم i
        if bit:                                    # إذا كان البت = 1
            result |= 1 << PBOX_INV[i]             # ضعه في مكانه الأصلي
    return result                                  # إرجاع الحالة الجديدة